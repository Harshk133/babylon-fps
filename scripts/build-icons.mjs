const RAW = "https://raw.githubusercontent.com/game-icons/icons/master";
const out = {};
const credits = new Set();
for (const [name, path] of Object.entries(ICONS)) {
  const r = await fetch(`${RAW}/${path}.svg`);
  if (!r.ok) throw new Error(`${path}: HTTP ${r.status}`);
  const svg = await r.text();
  // The first path is the black background square; the icon is the rest
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]).filter(d => !/^M0 0h512v512H0z$/.test(d));
  if (!paths.length) throw new Error(`${path}: no path`);
  out[name] = paths.join(" ");
  credits.add(path.split("/")[0]);
}

const body = Object.entries(out).map(([k, d]) => `  ${k}: "${d}",`).join("\n");
fs.writeFileSync("src/ui/gameIcons.js", `// Generated by scripts/build-icons.mjs: don't edit by hand.
// Icons from game-icons.net (CC BY 3.0) by ${[...credits].sort().join(", ")}.

/** name → SVG path data in a 512×512 box. */
export const ICON_PATHS = {
${body}
};

export const ICON_CREDITS = "Icons: game-icons.net (CC BY 3.0) by ${[...credits].sort().join(", ")}";

/** Inline SVG markup for an icon (fill follows the CSS colour). */
export function icon(name, cls = "") {
  const d = ICON_PATHS[name];
  return d ? \`<svg class="gi\${cls ? " " + cls : ""}" viewBox="0 0 512 512" aria-hidden="true"><path d="\${d}"/></svg>\` : "";
}

/** A data: URL of an icon in one colour, for <img> tags and canvas drawing. */
export function iconUrl(name, color = "#fff") {
  const d = ICON_PATHS[name];
  if (!d) return "";
  return "data:image/svg+xml;utf8," + encodeURIComponent(\`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><path fill="\${color}" d="\${d}"/></svg>\`);
}
`);
